using Azure.Messaging.ServiceBus;
using DocumentProcessingService.Application.DTOs;
using DocumentProcessingService.Application.Interfaces;
using DocumentProcessingService.Domain.Entities;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Logging;
using Newtonsoft.Json;
using System.Net.Sockets;

namespace DocumentProcessingService.Application.Services
{
    public class DocumentService : IDocumentService
    {
        private readonly IDocumentRepository _documentRepository;
        private readonly IBlobStorageService _documentStorage;
        private readonly IOutboxService _outboxService;
        private readonly ILogger<DocumentService> _logger;

        private static readonly Dictionary<string, string> AllowedFileTypes =
            new(StringComparer.OrdinalIgnoreCase)
            {
                        { ".pdf", "application/pdf" },
                        { ".png", "image/png" },
                        { ".jpg", "image/jpeg" },
                        { ".jpeg", "image/jpeg" }
            };

        public DocumentService(IDocumentRepository documentRepository, IBlobStorageService documentStorage,IOutboxService outboxService,
            ILogger<DocumentService> logger
            )
        {
            _documentRepository = documentRepository;
            _documentStorage = documentStorage;
            _outboxService = outboxService;
            _logger = logger;
        }

        public async Task<Document> CreateDocument(string fileName, long fileSize, string contentType, Stream fileStream, CancellationToken cancellationToken)
        {
            // Guard clauses - Validations
            if (string.IsNullOrWhiteSpace(fileName))
                throw new ArgumentException("File name cannot be empty.", nameof(fileName));

            string? fileExtension = Path.GetExtension(fileName);
            if (!AllowedFileTypes.TryGetValue(fileExtension, out _))
                throw new ArgumentException($"File type '{fileExtension}' is not supported.", nameof(fileName));

            var document = new Document()
            {
                FileName = fileName,
                ContentType = contentType,
                CreatedAt = DateTime.UtcNow,
            };

            string? blobName = null;

            try
            {
                // Step 1: Save metadata before uploading the file.
                _logger.LogInformation("Save document metadata started");
                document = await _documentRepository.AddDocumentAsync(document, cancellationToken);

                //Step2 : Save changes to get the document ID generated by the database.
                _logger.LogInformation("Persisting document to database");
                await _documentRepository.SaveAsync(cancellationToken);

                _logger.LogInformation("Document created with ID: {DocumentId}", document.Id);


                // STEP 3: Upload blob using now-available ID
                _logger.LogInformation("Document upload started");
                blobName = await _documentStorage.UploadDocumentAsync(
                    document.Id,
                    fileName,
                    fileStream,
                    cancellationToken);

                // Step 4: Update metadata after successful upload.
                document.BlobName = blobName;
                document.TryTransition(DocumentStatus.Uploaded);
                _documentRepository.Update(document, cancellationToken);
                _logger.LogInformation("Document {DocumentId} marked as Completed", document.Id);

                //STEP 5: Add an outbox message for the document creation event.
                await _outboxService.AddAsync(
                    "DocumentCreated",
                    JsonConvert.SerializeObject(new DocumentMessage{ DocumentId = document.Id, BlobName = document.BlobName, ContentType = document.ContentType }),
                    cancellationToken);

                // STEP 6: Save BOTH document update and outbox together (transactional)
                _logger.LogInformation("Persisting document update and outbox message together");
                await _documentRepository.SaveAsync(cancellationToken);

                return document;
            }
            catch (Exception ex)
            {
                _logger.LogError(ex,"Upload failed for document {DocumentId}",document.Id);
                // Compensation: remove the blob if it was uploaded.
                if (blobName is not null)
                {
                    try
                    {
                        await _documentStorage.DeleteAsync(
                            blobName,
                            CancellationToken.None);
                    }
                    catch (Exception cleanupException)
                    {
                        _logger.LogError(cleanupException, "Failed to delete blob {BlobName}", blobName);
                    }
                }
                // 2. Try to delete the document from database
                if (document.Id != Guid.Empty)  // Only if document was saved with an ID
                {
                    try
                    {
                        _logger.LogInformation("Attempting to delete document {DocumentId} from database as compensation", document.Id);
                        await _documentRepository.DeleteAsync(document.Id, CancellationToken.None);
                        _logger.LogInformation("Document {DocumentId} deleted from database", document.Id);
                    }
                    catch (Exception dbDeleteException)
                    {
                        // Fallback: mark as failed instead of deleting
                        _logger.LogInformation("Attempting to delete document {DocumentId} from database", document.Id);
                        try
                        {
                            document.TryTransition(DocumentStatus.Failed);
                            _documentRepository.Update(document, CancellationToken.None);
                            await _documentRepository.SaveAsync(CancellationToken.None);
                            _logger.LogInformation("Document {DocumentId} marked as Failed", document.Id);
                        }
                        catch (Exception markFailedException)
                        {
                            _logger.LogError(markFailedException, "Failed to mark document {DocumentId} as Failed", document.Id);
                        }
                    }
                }
                throw;
            }
        }

        public async Task<Document?> GetById(Guid documentId, CancellationToken cancellationToken)
        {
            if (documentId == Guid.Empty)
                throw new ArgumentException("Document ID cannot be empty.", nameof(documentId));

            Document? document = await _documentRepository.GetByIdAsync(documentId, cancellationToken);

            if(document == null)
            {
                return null;
            }

            return document;
        }

        public async Task<DocumentDownloadResult?> DownloadAsync(
            Guid documentId,
            CancellationToken cancellationToken)
        {
            Document? document = await _documentRepository.GetByIdAsync(
                documentId,
                cancellationToken);

            if (document is null ||
                document.Status != DocumentStatus.Completed)
            {
                return null;
            }

            var stream = await _documentStorage.DownloadAsync(
                document.BlobName,
                cancellationToken);

            return new DocumentDownloadResult(
                stream,
                document.FileName,
                document.ContentType);
        }
    }
}
